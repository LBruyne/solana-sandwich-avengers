"""Build the public sandwich-attacker dataset.

The script reads the per-category outputs of the sandwich-intent pipeline
(`sandwich-intent/data/3_attacker_filter/<category>/bot_*.parquet`), merges them
into a single de-categorized dataset, pulls the corresponding transaction
rows from ClickHouse, and writes the result under `dataset/`.

Outputs (epoch-tagged, default 946-960):

    dataset/attackers_<start>_<end>.parquet       # 1 row per attacker
    dataset/attackers_<start>_<end>.csv
    dataset/sandwiches_<start>_<end>.parquet      # 1 row per sandwich
    dataset/sandwiches_<start>_<end>.csv
    dataset/sandwich_txs_<start>_<end>.parquet    # 1 row per attacker/victim/adverse tx
    dataset/sandwich_txs_<start>_<end>.csv

Aux files (validators / token prices / sandwiched.me snapshot) are copied
to `dataset/aux/` once and not regenerated by this script.

Usage:
    python dataset/build_dataset.py                        # merge from existing sandwich-intent/data
    python dataset/build_dataset.py --rebuild              # also re-run sandwich-intent phases 1 + 3
    python dataset/build_dataset.py --start-epoch 946 --end-epoch 960
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
EVAL_DIR = REPO / "sandwich-intent"
EVAL_DATA = EVAL_DIR / "data"
DATASET_DIR = REPO / "dataset"

CATEGORIES = ["standard", "multi_split", "diff_signer_owner"]
CATEGORY_LABEL = {
    "standard": "standard",
    "multi_split": "multi-split",
    "diff_signer_owner": "diff-signer",
}
SLOTS_PER_EPOCH = 432_000

# CSV files are example slices, not the canonical dataset. They contain
# the union of "top X% by USD profit" and "top X% by sandwich count" so
# both the most profitable and the most active attackers are represented.
# Parquet files always carry the full dataset.
CSV_EXAMPLE_FRACTION = 0.03


# ── CLI ──────────────────────────────────────────────────────────────────────

def parse_args():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--start-epoch", type=int, default=946)
    p.add_argument("--end-epoch", type=int, default=960)
    p.add_argument("--rebuild", action="store_true",
                   help="Run sandwich-intent phase 1 and phase 3 for each category before merging.")
    p.add_argument("--no-tx-detail", action="store_true",
                   help="Skip sandwich_txs (avoids the ClickHouse query).")
    p.add_argument("--copy-aux", action="store_true",
                   help="Refresh dataset/aux/ from sandwich-intent/data/.")
    return p.parse_args()


# ── Phase orchestration ──────────────────────────────────────────────────────

def run_phases(start_epoch: int, end_epoch: int) -> None:
    """Invoke sandwich-intent phase 1 and phase 3 for each category, in order."""
    for cat in CATEGORIES:
        for script in ("1_signer_data_preparation_and_summary.py", "3_attacker_filter.py"):
            cmd = [sys.executable, script,
                   "--start-epoch", str(start_epoch),
                   "--end-epoch", str(end_epoch),
                   "--category", cat]
            print(f"\n$ (cd sandwich-intent && {' '.join(cmd)})")
            subprocess.run(cmd, check=True, cwd=str(EVAL_DIR))


# ── Load phase-3 outputs ─────────────────────────────────────────────────────

def load_phase3(tag: str) -> pd.DataFrame:
    """Concatenate bot_sandwiches across categories, keeping a `_category` column.

    Phase 3 stores the attacker entity in a column named `signer`; rename it
    to `attacker` here so the rest of the dataset uses the disambiguated name.
    """
    frames = []
    for cat in CATEGORIES:
        path = EVAL_DATA / "3_attacker_filter" / cat / f"bot_sandwiches_{tag}.parquet"
        if not path.exists():
            sys.exit(f"missing {path}; run with --rebuild or run sandwich-intent phases 1+3 first")
        df = pd.read_parquet(path)
        df = df.reset_index().rename(columns={"index": "sandwich_id",
                                               "signer": "attacker"})
        df["_category"] = cat
        frames.append(df)
    return pd.concat(frames, ignore_index=True)


# ── ClickHouse: pull sandwich_txs for our sandwich_ids ───────────────────────

def fetch_tx_rows(client, sandwich_ids: list[str]) -> pd.DataFrame:
    """Pull all sandwich_txs rows for the given sandwich_ids, batched."""
    chunks = []
    batch = 1000
    for i in range(0, len(sandwich_ids), batch):
        ids = sandwich_ids[i:i + batch]
        in_list = ",".join(f"'{s}'" for s in ids)
        q = f"""
            SELECT sandwichId, type, slot, position, signature, signers, inBundle,
                   programs, fromToken, toToken, fromAmount, toAmount, fee,
                   slippageUtilization
            FROM sandwich_txs
            WHERE sandwichId IN ({in_list})
              AND type IN ('frontRun', 'backRun', 'victim', 'adverse')
        """
        chunks.append(client.query_df(q))
    df = pd.concat(chunks, ignore_index=True)
    df = df.drop_duplicates(subset=["sandwichId", "type", "slot", "position"])
    return df


# ── Build outputs ────────────────────────────────────────────────────────────

def build_sandwiches(sw_raw: pd.DataFrame, tx_df: pd.DataFrame | None) -> pd.DataFrame:
    """Build sandwiches.parquet from per-category bot_sandwiches and tx rows."""
    sw = sw_raw.copy()
    sw["multi_split"] = sw["multi_front"] | sw["multi_back"]

    # Sandwich-level slippage: keep only [0, 1]; map -1/-2/-3 → NaN.
    sl = sw["slippage_consumption"]
    sw["slippage_consumption"] = sl.where((sl >= 0) & (sl <= 1), np.nan)

    sw = sw.rename(columns={"proximity": "fg", "back_gap": "bg"})

    # Attach front/victim/back signature lists from tx rows.
    if tx_df is not None:
        sigs = (tx_df[tx_df["type"].isin(["frontRun", "victim", "backRun"])]
                .groupby(["sandwichId", "type"])["signature"]
                .apply(list)
                .unstack("type"))
        for col in ("frontRun", "victim", "backRun"):
            if col not in sigs.columns:
                sigs[col] = [[] for _ in range(len(sigs))]
        sigs = sigs.rename(columns={"frontRun": "front_sig",
                                     "victim": "victim_sig",
                                     "backRun": "back_sig"})
        sw = sw.merge(sigs[["front_sig", "victim_sig", "back_sig"]],
                      left_on="sandwich_id", right_index=True, how="left")
        for col in ("front_sig", "victim_sig", "back_sig"):
            sw[col] = sw[col].apply(lambda v: v if isinstance(v, list) else [])
    else:
        sw["front_sig"] = [[]] * len(sw)
        sw["victim_sig"] = [[]] * len(sw)
        sw["back_sig"] = [[]] * len(sw)

    cols = [
        "sandwich_id", "attacker", "slot", "token_a", "token_b",
        "profit", "usd_profit", "is_profitable",
        "victim_count", "adverse_count",
        "cross_block", "multi_split", "front_count", "back_count",
        "slippage_consumption", "jito_bundle", "fg", "bg",
        "front_sig", "victim_sig", "back_sig",
    ]
    return sw[cols].sort_values(["slot", "sandwich_id"]).reset_index(drop=True)


def build_attackers(sandwiches: pd.DataFrame, sw_raw: pd.DataFrame,
                    diff_signer_n_keys: dict[str, int]) -> pd.DataFrame:
    """Aggregate per-attacker features from the merged sandwiches table."""
    g = sandwiches.groupby("attacker")

    # Per-attacker category set: the structural label for any sandwich the
    # attacker owns, plus "jito" if any of those sandwiches was a same-bundle.
    raw_cat_lookup = sw_raw.groupby("attacker")["_category"].agg(set)
    jito_flag = sandwiches.groupby("attacker")["jito_bundle"].any()

    def categories(attacker: str) -> list[str]:
        cats = {CATEGORY_LABEL[c] for c in raw_cat_lookup.loc[attacker]}
        if jito_flag.get(attacker, False):
            cats.add("jito")
        return sorted(cats)

    is_sol = sandwiches["token_a"] == "SOL"
    sol_profit = sandwiches["profit"].where(is_sol, 0.0)

    out = pd.DataFrame(index=g.size().index)
    out.index.name = "attacker"
    out["categories"] = [categories(a) for a in out.index]
    out["sandwich_count"] = g.size()
    out["profitable_count"] = g["is_profitable"].sum().astype(int)
    out["win_rate"] = out["profitable_count"] / out["sandwich_count"]
    out["usd_total_profit"] = g["usd_profit"].sum()
    out["usd_avg_profit"] = g["usd_profit"].mean()

    sol_g = sandwiches.assign(_sol_profit=sol_profit, _is_sol=is_sol).groupby("attacker")
    out["sol_total_profit"] = sol_g["_sol_profit"].sum()
    sol_count = sol_g["_is_sol"].sum().astype(int)
    out["sol_avg_profit"] = (out["sol_total_profit"] / sol_count.replace(0, np.nan))

    out["jito_count"] = g["jito_bundle"].sum().astype(int)
    out["jito_rate"] = out["jito_count"] / out["sandwich_count"]

    # mean over valid-range sandwich-level slippage; NaN if no valid samples.
    out["mean_slippage"] = g["slippage_consumption"].mean()

    out["median_proximity"] = g["fg"].median()
    out["fg1_ratio"] = g.apply(lambda d: float((d["fg"] == 1).mean()))
    out["fg100_ratio"] = g.apply(lambda d: float((d["fg"] <= 100).mean()))
    out["in_block_count"] = g.apply(lambda d: int((~d["cross_block"]).sum()))
    out["cross_block_count"] = g["cross_block"].sum().astype(int)
    out["multi_split_count"] = g["multi_split"].sum().astype(int)

    out["n_signing_keys"] = [diff_signer_n_keys.get(a, 1) for a in out.index]

    return out.reset_index().sort_values("usd_total_profit", ascending=False) \
              .reset_index(drop=True)


def build_sandwich_txs(tx_df: pd.DataFrame, sw_to_attacker: dict[str, str]) -> pd.DataFrame:
    """Format the tx-level rows for the public dataset."""
    df = tx_df.copy()
    df = df.rename(columns={
        "sandwichId": "sandwich_id",
        "fromToken": "from_token",
        "toToken": "to_token",
        "fromAmount": "from_amount",
        "toAmount": "to_amount",
        "inBundle": "in_bundle",
        "slippageUtilization": "slippage_consumption",
    })
    df["sandwich_attacker"] = df["sandwich_id"].map(sw_to_attacker)
    df["tx_signer"] = df["signers"].apply(lambda xs: xs[0] if isinstance(xs, (list, tuple, np.ndarray)) and len(xs) else None)

    # slippage only meaningful for victims; non-victim rows → NaN
    is_victim = df["type"] == "victim"
    df["slippage_consumption"] = df["slippage_consumption"].where(is_victim, np.nan)

    cols = [
        "sandwich_id", "sandwich_attacker", "type",
        "slot", "position", "signature", "tx_signer",
        "from_token", "to_token", "from_amount", "to_amount",
        "in_bundle", "fee", "programs",
        "slippage_consumption",
    ]
    return df[cols].sort_values(["sandwich_id", "slot", "position"]).reset_index(drop=True)


# ── n_signing_keys for diff_signer_owner entities ────────────────────────────

def diff_signer_keys_map(tag: str) -> dict[str, int]:
    """For diff_signer_owner entities, record how many on-chain signing keys
    were union-found into the entity. Read from phase-3's bot_attackers'
    n_signers column where present."""
    path = EVAL_DATA / "3_attacker_filter" / "diff_signer_owner" / f"bot_attackers_{tag}.parquet"
    if not path.exists():
        return {}
    sf = pd.read_parquet(path)
    if "n_signers" not in sf.columns:
        return {s: 1 for s in sf.index}
    return {s: int(n) for s, n in sf["n_signers"].items()}


# ── Aux files ────────────────────────────────────────────────────────────────

def copy_aux() -> None:
    aux_dir = DATASET_DIR / "aux"
    aux_dir.mkdir(parents=True, exist_ok=True)
    pairs = [
        (EVAL_DATA / "stakewiz" / "validators.csv", aux_dir / "validators.csv"),
        (EVAL_DATA / "token_prices" / "prices.csv", aux_dir / "token_prices.csv"),
        (EVAL_DATA / "sandwiches_site_epoch_946.csv",
         aux_dir / "sandwiched_me_epoch_946.csv"),
    ]
    for src, dst in pairs:
        if not src.exists():
            print(f"  skip {src.name}: source missing")
            continue
        shutil.copyfile(src, dst)
        print(f"  copied {src.name} -> {dst.relative_to(REPO)}")


# ── Main ─────────────────────────────────────────────────────────────────────

def main() -> None:
    args = parse_args()
    tag = f"{args.start_epoch}_{args.end_epoch}"
    DATASET_DIR.mkdir(exist_ok=True)

    if args.rebuild:
        print(f"=== Rebuilding sandwich-intent/data/ for epochs {args.start_epoch}-{args.end_epoch} ===")
        run_phases(args.start_epoch, args.end_epoch)

    print(f"=== Loading sandwich-intent phase-3 outputs (tag={tag}) ===")
    sw_raw = load_phase3(tag)
    print(f"  raw sandwiches across categories: {len(sw_raw):,}")
    print(f"  unique attackers: {sw_raw['attacker'].nunique():,}")
    sw_to_attacker = dict(zip(sw_raw["sandwich_id"], sw_raw["attacker"]))

    tx_df = None
    if not args.no_tx_detail:
        print("=== Querying ClickHouse for tx-level rows ===")
        # Lazy import so --no-tx-detail works without a ClickHouse install.
        sys.path.insert(0, str(EVAL_DIR))
        from utils.db import get_client  # type: ignore
        client = get_client()
        ids = sorted(set(sw_raw["sandwich_id"]))
        tx_df = fetch_tx_rows(client, ids)
        print(f"  fetched {len(tx_df):,} tx rows for {len(ids):,} sandwiches")

    print("=== Building sandwiches table ===")
    sandwiches = build_sandwiches(sw_raw, tx_df)
    print(f"  {len(sandwiches):,} rows")

    print("=== Building attackers table ===")
    n_keys = diff_signer_keys_map(tag)
    attackers = build_attackers(sandwiches, sw_raw, n_keys)
    print(f"  {len(attackers):,} unique attackers")

    # CSV example slice: union of top-X% by USD profit and top-X% by
    # sandwich count, so both the most profitable and the most active
    # attackers are represented. Parquet keeps the full table.
    n_top = max(1, int(np.ceil(len(attackers) * CSV_EXAMPLE_FRACTION)))
    top_usd = set(attackers.nlargest(n_top, "usd_total_profit")["attacker"])
    top_cnt = set(attackers.nlargest(n_top, "sandwich_count")["attacker"])
    top_attackers = top_usd | top_cnt
    print(f"  CSV example slice: top {CSV_EXAMPLE_FRACTION:.0%} by USD ({len(top_usd)}) "
          f"∪ top {CSV_EXAMPLE_FRACTION:.0%} by count ({len(top_cnt)}) "
          f"= {len(top_attackers)} attackers")

    at_path_p = DATASET_DIR / f"attackers_{tag}.parquet"
    at_path_c = DATASET_DIR / f"attackers_{tag}.csv"
    sw_path_p = DATASET_DIR / f"sandwiches_{tag}.parquet"
    sw_path_c = DATASET_DIR / f"sandwiches_{tag}.csv"
    attackers.to_parquet(at_path_p, index=False, compression="zstd")
    sandwiches.to_parquet(sw_path_p, index=False, compression="zstd")
    attackers[attackers["attacker"].isin(top_attackers)].to_csv(at_path_c, index=False)
    sandwiches[sandwiches["attacker"].isin(top_attackers)].to_csv(sw_path_c, index=False)
    print(f"  wrote {at_path_p.name}, {at_path_c.name}, {sw_path_p.name}, {sw_path_c.name}")

    if tx_df is not None:
        print("=== Building sandwich_txs table ===")
        sw_txs = build_sandwich_txs(tx_df, sw_to_attacker)
        print(f"  {len(sw_txs):,} rows")
        tx_path_p = DATASET_DIR / f"sandwich_txs_{tag}.parquet"
        tx_path_c = DATASET_DIR / f"sandwich_txs_{tag}.csv"
        sw_txs.to_parquet(tx_path_p, index=False, compression="zstd")
        sw_txs[sw_txs["sandwich_attacker"].isin(top_attackers)].to_csv(tx_path_c, index=False)
        print(f"  wrote {tx_path_p.name}, {tx_path_c.name}")

    if args.copy_aux:
        print("=== Copying aux files ===")
        copy_aux()

    print("\nDone.")


if __name__ == "__main__":
    main()
